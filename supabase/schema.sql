/* =========================================================
   13. POSTS POLICIES
   ========================================================= */

/*
  Everyone can read published posts.
*/

create policy
  "posts_public_select"

on public.posts

for select

to anon, authenticated

using (
  status = 'published'
);


/*
  Visitors can create published posts.

  They cannot insert:
  hidden / deleted
  posts through the public browser API.
*/

create policy
  "posts_public_insert"

on public.posts

for insert

to anon, authenticated

with check (
  status = 'published'
);


/* =========================================================
   14. COMMENTS POLICIES
   ========================================================= */

/*
  Everyone can read published comments.
*/

create policy
  "comments_public_select"

on public.comments

for select

to anon, authenticated

using (
  status = 'published'
);


/*
  Everyone can create published comments.
*/

create policy
  "comments_public_insert"

on public.comments

for insert

to anon, authenticated

with check (
  status = 'published'
);


/* =========================================================
   15. REACTIONS POLICIES
   ========================================================= */

/*
  Visitors can insert likes.

  The unique constraint prevents the same
  visitor from liking the same post twice.
*/

create policy
  "reactions_public_insert"

on public.reactions

for insert

to anon, authenticated

with check (
  type = 'like'
);


/*
  IMPORTANT:
  No public SELECT policy is created for reactions.

  Visitors therefore cannot browse every visitor_id.

  The frontend keeps local like state in LocalStorage,
  while posts.like_count is maintained by triggers.
*/


/* =========================================================
   16. REPORT POLICIES
   ========================================================= */

/*
  Visitors may submit reports.
*/

create policy
  "reports_public_insert"

on public.reports

for insert

to anon, authenticated

with check (
  true
);


/*
  IMPORTANT:
  No SELECT policy for reports.

  Ordinary visitors cannot read reports.
*/


