/* =========================================================
   2. POSTS
   ========================================================= */

create table if not exists public.posts (

  id bigint generated by default as identity
    primary key,

  nickname text
    not null
    default '匿名用户',

  title text
    not null,

  category text
    not null,

  content text
    not null,

  status text
    not null
    default 'published',

  like_count integer
    not null
    default 0,

  created_at timestamptz
    not null
    default now(),

  updated_at timestamptz
    not null
    default now(),

  constraint posts_nickname_length
    check (
      char_length(nickname)
      between 1 and 30
    ),

  constraint posts_title_length
    check (
      char_length(title)
      between 1 and 100
    ),

  constraint posts_content_length
    check (
      char_length(content)
      between 1 and 5000
    ),

  constraint posts_category_check
    check (
      category in (
        '校园生活',
        '学习压力',
        '食堂住宿',
        '老师教学',
        '社团活动',
        '校园设施',
        '其他'
      )
    ),

  constraint posts_status_check
    check (
      status in (
        'published',
        'hidden',
        'deleted'
      )
    ),

  constraint posts_like_count_check
    check (
      like_count >= 0
    )

);


/* =========================================================
   3. COMMENTS
   ========================================================= */

create table if not exists public.comments (

  id bigint generated by default as identity
    primary key,

  post_id bigint
    not null
    references public.posts(id)
    on delete cascade,

  nickname text
    not null
    default '匿名用户',

  content text
    not null,

  status text
    not null
    default 'published',

  created_at timestamptz
    not null
    default now(),

  updated_at timestamptz
    not null
    default now(),

  constraint comments_nickname_length
    check (
      char_length(nickname)
      between 1 and 30
    ),

  constraint comments_content_length
    check (
      char_length(content)
      between 1 and 500
    ),

  constraint comments_status_check
    check (
      status in (
        'published',
        'hidden',
        'deleted'
      )
    )

);


/* =========================================================
   4. REACTIONS
   ========================================================= */

create table if not exists public.reactions (

  id bigint generated by default as identity
    primary key,

  post_id bigint
    not null
    references public.posts(id)
    on delete cascade,

  visitor_id uuid
    not null,

  type text
    not null
    default 'like',

  created_at timestamptz
    not null
    default now(),

  constraint reactions_type_check
    check (
      type = 'like'
    ),

  constraint reactions_unique_like
    unique (
      post_id,
      visitor_id,
      type
    )

);


/* =========================================================
   5. REPORTS
   ========================================================= */

create table if not exists public.reports (

  id bigint generated by default as identity
    primary key,

  post_id bigint
    not null
    references public.posts(id)
    on delete cascade,

  visitor_id uuid
    not null,

  reason text
    not null,

  created_at timestamptz
    not null
    default now(),

  constraint reports_reason_check
    check (
      reason in (
        'spam',
        'privacy',
        'harassment',
        'false_information',
        'other'
      )
    )

);


