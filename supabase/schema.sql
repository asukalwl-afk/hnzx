/* =========================================================
   19. SECURITY HARDENING
   ========================================================= */

/*
  Do not allow anonymous users to update/delete rows.

  We intentionally do NOT grant:
    update
    delete

  to anon/authenticated.

  This means the public browser can:
    SELECT published posts
    INSERT posts
    SELECT published comments
    INSERT comments
    INSERT reactions
    INSERT reports

  but cannot directly:
    UPDATE posts
    DELETE posts
    UPDATE comments
    DELETE comments
    DELETE reactions
    READ reports
*/


/* =========================================================
   20. REPAIR LIKE COUNTS
   ========================================================= */

/*
  Run this if the database already had reactions
  before this schema was installed.
*/

update public.posts p

set like_count = (

  select count(*)::integer

  from public.reactions r

  where r.post_id = p.id

  and r.type = 'like'

);


/* =========================================================
   21. OPTIONAL DEFAULT PRIVILEGE HARDENING
   ========================================================= */

/*
  This section prevents future public tables from
  automatically receiving broad Data API privileges.

  Existing tables above already have explicit grants.

  If you create future public tables, grant only the
  permissions they actually need.
*/


alter default privileges
in schema public

revoke
  all
on tables
from anon, authenticated;


