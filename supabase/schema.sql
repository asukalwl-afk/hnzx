/* =========================================================
   7. UPDATED_AT FUNCTION
   ========================================================= */

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin

  new.updated_at = now();

  return new;

end;
$$;


/* =========================================================
   8. UPDATED_AT TRIGGERS
   ========================================================= */

drop trigger if exists
  posts_set_updated_at
on public.posts;


create trigger
  posts_set_updated_at

before update
on public.posts

for each row
execute function public.set_updated_at();


drop trigger if exists
  comments_set_updated_at
on public.comments;


create trigger
  comments_set_updated_at

before update
on public.comments

for each row
execute function public.set_updated_at();


/* =========================================================
   9. LIKE COUNT FUNCTIONS
   ========================================================= */

create or replace function public.increment_post_like_count()
returns trigger
language plpgsql
security invoker
as $$
begin

  update public.posts

  set like_count =
    like_count + 1

  where id = new.post_id;

  return new;

end;
$$;


create or replace function public.decrement_post_like_count()
returns trigger
language plpgsql
security invoker
as $$
begin

  update public.posts

  set like_count =
    greatest(
      like_count - 1,
      0
    )

  where id = old.post_id;

  return old;

end;
$$;


